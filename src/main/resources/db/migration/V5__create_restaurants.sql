COMMENT ON COLUMN restaurants.google_place_id IS 'Google Places 식당 식별자';
COMMENT ON COLUMN restaurants.external_rating IS '외부 공급자의 사용자 평점';
COMMENT ON COLUMN restaurants.external_rating_count IS '외부 공급자의 평가 수';
