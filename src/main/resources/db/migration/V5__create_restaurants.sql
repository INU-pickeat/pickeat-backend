    ADD COLUMN IF NOT EXISTS representative_image_url VARCHAR(1000),
    ADD COLUMN IF NOT EXISTS external_data_refreshed_at TIMESTAMPTZ;

CREATE UNIQUE INDEX IF NOT EXISTS restaurants_google_place_id_unique_idx
    ON restaurants (google_place_id)
    WHERE google_place_id IS NOT NULL;

COMMENT ON TABLE restaurants IS 'Pick Eat 추천 및 Pick 기록에서 사용하는 식당 정보';
