CREATE TABLE IF NOT EXISTS restaurants (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_provider               VARCHAR(20) NOT NULL DEFAULT 'GOOGLE',
    google_place_id             VARCHAR(255),
    name                        VARCHAR(200) NOT NULL,
    food_category               VARCHAR(30),
    address                     VARCHAR(500),
    latitude                    DOUBLE PRECISION NOT NULL,
    longitude                   DOUBLE PRECISION NOT NULL,
    phone_number                VARCHAR(50),
    opening_hours_text          TEXT,
    external_rating             NUMERIC(2, 1),
    external_rating_count       INTEGER,
    price_level                 VARCHAR(30),
    representative_image_url    VARCHAR(1000),
    external_data_refreshed_at  TIMESTAMPTZ,
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT restaurants_name_not_blank CHECK (LENGTH(TRIM(name)) > 0),
    CONSTRAINT restaurants_provider_not_blank CHECK (LENGTH(TRIM(data_provider)) > 0),
    CONSTRAINT restaurants_place_id_not_blank
        CHECK (google_place_id IS NULL OR LENGTH(TRIM(google_place_id)) > 0),
    CONSTRAINT restaurants_latitude_range CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT restaurants_longitude_range CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT restaurants_external_rating_range
        CHECK (external_rating IS NULL OR external_rating BETWEEN 0 AND 5),
    CONSTRAINT restaurants_external_rating_count_non_negative
        CHECK (external_rating_count IS NULL OR external_rating_count >= 0),
    CONSTRAINT restaurants_food_category
        CHECK (food_category IS NULL OR food_category IN (
            'KOREAN', 'JAPANESE', 'CHINESE', 'WESTERN', 'CAFE_DESSERT'
        ))
);

